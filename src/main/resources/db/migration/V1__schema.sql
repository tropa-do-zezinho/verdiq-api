    CONSTRAINT fk_sin_produto FOREIGN KEY (produto_id) REFERENCES produto(id) ON DELETE CASCADE,
    CONSTRAINT uq_produto_sinonimo UNIQUE (produto_id, sinonimo)
);

CREATE TABLE produto_substituto (
    produto_id      NUMBER(19) NOT NULL,
    substituto_id   NUMBER(19) NOT NULL,
    PRIMARY KEY (produto_id, substituto_id),
    CONSTRAINT fk_sub_prod FOREIGN KEY (produto_id) REFERENCES produto(id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_sub FOREIGN KEY (substituto_id) REFERENCES produto(id) ON DELETE CASCADE,
    CONSTRAINT ck_sub_diff CHECK (produto_id <> substituto_id)
);

CREATE TABLE cliente_interesse (
