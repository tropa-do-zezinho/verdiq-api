-- Verdiq schema (Oracle) — America/Sao_Paulo via app

CREATE TABLE usuario (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome            VARCHAR2(120) NOT NULL,
    email           VARCHAR2(180) UNIQUE,
    telefone        VARCHAR2(20) UNIQUE,
    senha_hash      VARCHAR2(255) NOT NULL,
    papel           VARCHAR2(20) NOT NULL CHECK (papel IN ('COMERCIANTE', 'CLIENTE', 'ADMIN')),
    cidade          VARCHAR2(120),
    uf              VARCHAR2(2) DEFAULT 'SP',
    consentimento_notificacoes NUMBER(1) NOT NULL DEFAULT 0 CHECK (consentimento_notificacoes IN (0,1)),
    consentimento_comparativos NUMBER(1) NOT NULL DEFAULT 0 CHECK (consentimento_comparativos IN (0,1)),
    ativo           NUMBER(1) NOT NULL DEFAULT 1 CHECK (ativo IN (0,1)),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    excluido_em     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE refresh_token (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    token_hash      VARCHAR2(128) NOT NULL UNIQUE,
    expira_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    revogado        NUMBER(1) NOT NULL DEFAULT 0 CHECK (revogado IN (0,1)),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE password_reset_token (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    token_hash      VARCHAR2(128) NOT NULL UNIQUE,
    expira_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    usado           NUMBER(1) NOT NULL DEFAULT 0 CHECK (usado IN (0,1)),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE praca (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR2(40) NOT NULL UNIQUE,
    nome            VARCHAR2(120) NOT NULL,
    cidade          VARCHAR2(120) NOT NULL,
    uf              VARCHAR2(2) NOT NULL,
    fonte           VARCHAR2(40) NOT NULL DEFAULT 'PROHORT'
);

CREATE TABLE comerciante (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    nome_fantasia   VARCHAR2(160) NOT NULL,
    tipo_negocio    VARCHAR2(60) NOT NULL,
    praca_id        NUMBER(19) REFERENCES praca(id),
    plano           VARCHAR2(20) NOT NULL DEFAULT 'ESSENCIAL' CHECK (plano IN ('ESSENCIAL', 'PRO')),
    latitude        BINARY_DOUBLE,
    longitude       BINARY_DOUBLE,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cliente_perfil (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    cidade          VARCHAR2(120),
    uf              VARCHAR2(2) DEFAULT 'SP',
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE produto (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome_canonico   VARCHAR2(120) NOT NULL UNIQUE,
    categoria       VARCHAR2(40) NOT NULL CHECK (categoria IN ('FRUTA', 'LEGUME', 'VERDURA', 'OUTRO')),
    unidade_base    VARCHAR2(10) NOT NULL DEFAULT 'KG',
    perecivel       NUMBER(1) NOT NULL DEFAULT 1 CHECK (perecivel IN (0,1)),
    ativo           NUMBER(1) NOT NULL DEFAULT 1 CHECK (ativo IN (0,1)),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE produto_sinonimo (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    sinonimo        VARCHAR2(120) NOT NULL,
    CONSTRAINT uq_produto_sinonimo UNIQUE (produto_id, sinonimo)
);

CREATE TABLE produto_substituto (
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    substituto_id   NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (produto_id, substituto_id),
    CHECK (produto_id <> substituto_id)
);

CREATE TABLE cliente_interesse (
    cliente_perfil_id NUMBER(19) NOT NULL REFERENCES cliente_perfil(id) ON DELETE CASCADE,
    produto_id        NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (cliente_perfil_id, produto_id)
);

CREATE TABLE comerciante_produto_principal (
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (comerciante_id, produto_id)
);

CREATE TABLE preco_mercado (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    praca_id        NUMBER(19) NOT NULL REFERENCES praca(id),
    data_ref        DATE NOT NULL,
    preco_medio     NUMBER(12,4) NOT NULL,
    volume_kg       NUMBER(14,3),
    fonte           VARCHAR2(40) NOT NULL,
    coletado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_preco_mercado UNIQUE (produto_id, praca_id, data_ref, fonte)
);

CREATE INDEX idx_preco_mercado_produto_data ON preco_mercado (produto_id, data_ref);

CREATE TABLE producao (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    uf              VARCHAR2(2) NOT NULL,
    municipio       VARCHAR2(120),
    ano             NUMBER(10) NOT NULL,
    area_ha         NUMBER(14,2),
    producao_t      NUMBER(14,2),
    rendimento      NUMBER(14,2),
    valor_rs        NUMBER(16,2),
    fonte           VARCHAR2(40) NOT NULL DEFAULT 'IBGE_PAM',
    coletado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_producao UNIQUE (produto_id, uf, municipio, ano, fonte)
);

CREATE TABLE clima_obs (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    estacao_codigo  VARCHAR2(20) NOT NULL,
    data_ref        DATE NOT NULL,
    chuva_mm        NUMBER(10,2),
    temp_min        NUMBER(6,2),
    temp_max        NUMBER(6,2),
    fonte           VARCHAR2(40) NOT NULL DEFAULT 'UPLOAD',
    coletado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_clima_obs UNIQUE (estacao_codigo, data_ref, fonte)
);

CREATE TABLE ipca_mensal (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ano_mes         VARCHAR2(7) NOT NULL UNIQUE,
    indice          NUMBER(12,4) NOT NULL,
    fonte           VARCHAR2(40) NOT NULL DEFAULT 'BCB_SGS_433',
    coletado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE indice_sazonal (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    praca_id        NUMBER(19) REFERENCES praca(id),
    comerciante_id  NUMBER(19) REFERENCES comerciante(id),
    mes             NUMBER(10) NOT NULL CHECK (mes BETWEEN 1 AND 12),
    tipo            VARCHAR2(20) NOT NULL CHECK (tipo IN ('PRECO', 'OFERTA', 'VENDAS')),
    valor           NUMBER(10,4) NOT NULL,
    anos_usados     NUMBER(10) NOT NULL,
    confianca       VARCHAR2(20) NOT NULL CHECK (confianca IN ('ALTA', 'MEDIA', 'BAIXA', 'INSUFICIENTE')),
    calculado_em    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_indice_sazonal ON indice_sazonal (
    produto_id, praca_id, NVL(comerciante_id, -1), mes, tipo
);

CREATE TABLE evento_sazonal (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    nome            VARCHAR2(80) NOT NULL,
    regra_data      VARCHAR2(120) NOT NULL,
    mes_tipico      NUMBER(10),
    descricao       CLOB
);

CREATE TABLE evento_produto (
    evento_id       NUMBER(19) NOT NULL REFERENCES evento_sazonal(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (evento_id, produto_id)
);

CREATE TABLE lote_envio (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    tipo            VARCHAR2(20) NOT NULL CHECK (tipo IN ('COMPRA', 'VENDA', 'PERDA', 'IMPORT')),
    origem          VARCHAR2(40) NOT NULL DEFAULT 'MANUAL',
    arquivo_nome    VARCHAR2(255),
    qtd_linhas      NUMBER(10) NOT NULL DEFAULT 0,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE compra (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    lote_envio_id   NUMBER(19) REFERENCES lote_envio(id),
    kg              NUMBER(12,3) NOT NULL,
    valor_total     NUMBER(14,2) NOT NULL,
    valor_unitario_envio NUMBER(14,4) NOT NULL,
    data_ref        DATE NOT NULL,
    fornecedor      VARCHAR2(160),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE venda (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    lote_envio_id   NUMBER(19) REFERENCES lote_envio(id),
    kg              NUMBER(12,3) NOT NULL,
    valor_total     NUMBER(14,2) NOT NULL,
    valor_unitario_envio NUMBER(14,4) NOT NULL,
    data_ref        DATE NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE perda (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    lote_envio_id   NUMBER(19) REFERENCES lote_envio(id),
    kg              NUMBER(12,3) NOT NULL,
    motivo          VARCHAR2(40) NOT NULL CHECK (motivo IN ('ESTRAGOU', 'SOBRA', 'QUEDA', 'DEVOLUCAO', 'OUTRO')),
    valor_estimado_envio NUMBER(14,2),
    data_ref        DATE NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE oferta (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    preco_normal    NUMBER(12,2) NOT NULL,
    preco_promocional NUMBER(12,2) NOT NULL,
    quantidade_kg   NUMBER(12,3),
    inicio          DATE NOT NULL,
    fim             DATE NOT NULL,
    status          VARCHAR2(20) NOT NULL DEFAULT 'ATIVA' CHECK (status IN ('ATIVA', 'ENCERRADA', 'REVISAO', 'REMOVIDA')),
    ultima_chance   NUMBER(1) NOT NULL DEFAULT 0 CHECK (ultima_chance IN (0,1)),
    lote_info       VARCHAR2(160),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (preco_promocional < preco_normal),
    CHECK (fim >= inicio)
);

CREATE TABLE oferta_denuncia (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    oferta_id       NUMBER(19) NOT NULL REFERENCES oferta(id) ON DELETE CASCADE,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    motivo          VARCHAR2(255),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_oferta_denuncia UNIQUE (oferta_id, usuario_id)
);

CREATE TABLE favorito_produto (
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, produto_id)
);

CREATE TABLE favorito_comerciante (
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    comerciante_id  NUMBER(19) NOT NULL REFERENCES comerciante(id) ON DELETE CASCADE,
    PRIMARY KEY (usuario_id, comerciante_id)
);

CREATE TABLE lista_compras_epoca (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    nome            VARCHAR2(120) NOT NULL DEFAULT 'Lista da vez',
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE lista_compras_item (
    lista_id        NUMBER(19) NOT NULL REFERENCES lista_compras_epoca(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id) ON DELETE CASCADE,
    PRIMARY KEY (lista_id, produto_id)
);

CREATE TABLE preferencia_notificacao (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    canal_web_push  NUMBER(1) NOT NULL DEFAULT 0 CHECK (canal_web_push IN (0,1)),
    canal_in_app    NUMBER(1) NOT NULL DEFAULT 1 CHECK (canal_in_app IN (0,1)),
    max_por_semana  NUMBER(10) NOT NULL DEFAULT 3,
    hora_inicio     NUMBER(10) NOT NULL DEFAULT 8,
    hora_fim        NUMBER(10) NOT NULL DEFAULT 20,
    tipos_alerta    VARCHAR2(255) NOT NULL DEFAULT 'JANELA_COMPRA,EM_SAFRA,RISCO_PERDA,PRECO_ALTO'
);

CREATE TABLE web_push_subscription (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    endpoint        VARCHAR2(4000) NOT NULL UNIQUE,
    p256dh          VARCHAR2(512) NOT NULL,
    auth            VARCHAR2(512) NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notificacao (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    titulo          VARCHAR2(160) NOT NULL,
    corpo           CLOB NOT NULL,
    tipo            VARCHAR2(40) NOT NULL,
    lida            NUMBER(1) NOT NULL DEFAULT 0 CHECK (lida IN (0,1)),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE plano (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR2(20) NOT NULL UNIQUE,
    nome            VARCHAR2(80) NOT NULL,
    preco_mensal    NUMBER(10,2) NOT NULL,
    beneficios      CLOB NOT NULL,
    ativo           NUMBER(1) NOT NULL DEFAULT 1 CHECK (ativo IN (0,1))
);

CREATE TABLE interesse_plano (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    plano_id        NUMBER(19) NOT NULL REFERENCES plano(id),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE etl_run (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    fonte           VARCHAR2(40) NOT NULL,
    status          VARCHAR2(20) NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED', 'PARTIAL')),
    iniciado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizado_em   TIMESTAMP WITH TIME ZONE,
    registros       NUMBER(10) DEFAULT 0,
    mensagem        CLOB,
    autor_usuario_id NUMBER(19) REFERENCES usuario(id)
);

CREATE TABLE etl_raw (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    etl_run_id      NUMBER(19) NOT NULL REFERENCES etl_run(id) ON DELETE CASCADE,
    fonte           VARCHAR2(40) NOT NULL,
    payload         CLOB NOT NULL,
    coletado_em     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE market_upload (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL REFERENCES usuario(id),
    tipo            VARCHAR2(40) NOT NULL,
    arquivo_nome    VARCHAR2(255) NOT NULL,
    status          VARCHAR2(20) NOT NULL DEFAULT 'VALIDADO',
    qtd_linhas      NUMBER(10) NOT NULL DEFAULT 0,
    mensagem        CLOB,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_log (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) REFERENCES usuario(id),
    acao            VARCHAR2(80) NOT NULL,
    detalhe         CLOB,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recomendacao (
    id              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) REFERENCES comerciante(id) ON DELETE CASCADE,
    produto_id      NUMBER(19) NOT NULL REFERENCES produto(id),
    tipo            VARCHAR2(40) NOT NULL,
    titulo          VARCHAR2(200) NOT NULL,
    mensagem        CLOB NOT NULL,
    confianca       VARCHAR2(20) NOT NULL,
    dados_json      CLOB NOT NULL,
    periodo_inicio  DATE,
    periodo_fim     DATE,
    fonte           VARCHAR2(80) NOT NULL,
    gerado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_recomendacao_comerciante ON recomendacao (comerciante_id, gerado_em);
CREATE INDEX idx_oferta_ativa ON oferta (status, fim);
CREATE INDEX idx_notificacao_usuario ON notificacao (usuario_id, criado_em);
