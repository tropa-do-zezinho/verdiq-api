CREATE TABLE produto (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_canonico   VARCHAR2(120) NOT NULL UNIQUE,
    categoria       VARCHAR2(40) NOT NULL,
    unidade_base    VARCHAR2(10) DEFAULT 'KG' NOT NULL,
    perecivel       NUMBER(1) DEFAULT 1 NOT NULL,
    ativo           NUMBER(1) DEFAULT 1 NOT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_prod_cat CHECK (categoria IN ('FRUTA', 'LEGUME', 'VERDURA', 'OUTRO')),
    CONSTRAINT ck_prod_perecivel CHECK (perecivel IN (0, 1)),
    CONSTRAINT ck_prod_ativo CHECK (ativo IN (0, 1))
);

CREATE TABLE produto_sinonimo (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
