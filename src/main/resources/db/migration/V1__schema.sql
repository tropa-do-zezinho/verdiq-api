-- Verdiq schema (Oracle 19) — DEFAULT antes de NOT NULL

CREATE TABLE usuario (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR2(120) NOT NULL,
    email           VARCHAR2(180) UNIQUE,
    telefone        VARCHAR2(20) UNIQUE,
    senha_hash      VARCHAR2(255) NOT NULL,
    papel           VARCHAR2(20) NOT NULL,
    cidade          VARCHAR2(120),
    uf              VARCHAR2(2) DEFAULT 'SP',
    consentimento_notificacoes NUMBER(1) DEFAULT 0 NOT NULL,
    consentimento_comparativos NUMBER(1) DEFAULT 0 NOT NULL,
    ativo           NUMBER(1) DEFAULT 1 NOT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    atualizado_em   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    excluido_em     TIMESTAMP,
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('COMERCIANTE', 'CLIENTE', 'ADMIN')),
    CONSTRAINT ck_usuario_notif CHECK (consentimento_notificacoes IN (0, 1)),
    CONSTRAINT ck_usuario_comp CHECK (consentimento_comparativos IN (0, 1)),
    CONSTRAINT ck_usuario_ativo CHECK (ativo IN (0, 1))
);

CREATE TABLE refresh_token (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL,
    token_hash      VARCHAR2(128) NOT NULL UNIQUE,
    expira_em       TIMESTAMP NOT NULL,
    revogado        NUMBER(1) DEFAULT 0 NOT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT ck_refresh_revogado CHECK (revogado IN (0, 1))
);

CREATE TABLE password_reset_token (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL,
    token_hash      VARCHAR2(128) NOT NULL UNIQUE,
    expira_em       TIMESTAMP NOT NULL,
    usado           NUMBER(1) DEFAULT 0 NOT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_pwd_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT ck_pwd_usado CHECK (usado IN (0, 1))
);

CREATE TABLE praca (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR2(40) NOT NULL UNIQUE,
    nome            VARCHAR2(120) NOT NULL,
    cidade          VARCHAR2(120) NOT NULL,
    uf              VARCHAR2(2) NOT NULL,
    fonte           VARCHAR2(40) DEFAULT 'PROHORT' NOT NULL
);

CREATE TABLE comerciante (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      NUMBER(19) NOT NULL UNIQUE,
    nome_fantasia   VARCHAR2(160) NOT NULL,
    tipo_negocio    VARCHAR2(60) NOT NULL,
    praca_id        NUMBER(19),
