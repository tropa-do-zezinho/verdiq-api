CREATE TABLE oferta (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comerciante_id  NUMBER(19) NOT NULL,
    produto_id      NUMBER(19) NOT NULL,
    preco_normal    NUMBER(12,2) NOT NULL,
    preco_promocional NUMBER(12,2) NOT NULL,
    quantidade_kg   NUMBER(12,3),
    inicio          DATE NOT NULL,
    fim             DATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ATIVA' NOT NULL,
    ultima_chance   NUMBER(1) DEFAULT 0 NOT NULL,
    lote_info       VARCHAR2(160),
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_oferta_com FOREIGN KEY (comerciante_id) REFERENCES comerciante(id) ON DELETE CASCADE,
    CONSTRAINT fk_oferta_prod FOREIGN KEY (produto_id) REFERENCES produto(id),
    CONSTRAINT ck_oferta_status CHECK (status IN ('ATIVA', 'ENCERRADA', 'REVISAO', 'REMOVIDA')),
    CONSTRAINT ck_oferta_chance CHECK (ultima_chance IN (0, 1)),
    CONSTRAINT ck_oferta_preco CHECK (preco_promocional < preco_normal),
    CONSTRAINT ck_oferta_datas CHECK (fim >= inicio)
);

